/**
 * Best-effort default country from the browser locale's region subtag
 * (e.g. "en-IN" → "India"). Returns undefined when no match is found.
 */
export const guessCountryFromLocale = (): string | undefined => {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    const region = new Intl.Locale(locale).region;
    if (!region) return undefined;
    const displayName = new Intl.DisplayNames(['en'], { type: 'region' }).of(region);
    if (!displayName) return undefined;
    return COUNTRIES.find(
      (country) =>
        country.toLowerCase() === displayName.toLowerCase() ||
        displayName.toLowerCase().includes(country.toLowerCase()),
    );
  } catch {
    return undefined;
  }
};

interface CountryComboboxProps {
  value: string;
  onChange: (value: string) => void;
  placeholder?: string;
  disabled?: boolean;
  /** Forwarded to the trigger for label association. */
  id?: string;
  className?: string;
}

export function CountryCombobox({
  value,
  onChange,
  placeholder = 'Select your country',
  disabled,
  id,
  className,
}: CountryComboboxProps) {
  const [open, setOpen] = useState(false);

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <Button
          id={id}
          type="button"
          variant="outline"
          role="combobox"
          aria-expanded={open}
          disabled={disabled}
          className={cn(
            'w-full justify-between font-normal',
            !value && 'text-muted-foreground',
            className,
          )}
        >
          <span className="truncate">{value || placeholder}</span>
          <ChevronsUpDown className="ml-2 h-4 w-4 shrink-0 opacity-50" aria-hidden />
        </Button>
      </PopoverTrigger>
      <PopoverContent className="w-[--radix-popover-trigger-width] p-0" align="start">
        <Command>
          <CommandInput placeholder="Search countries…" />
          <CommandList>
            <CommandEmpty>No country found.</CommandEmpty>
            <CommandGroup>
              {COUNTRIES.map((country) => (
                <CommandItem
                  key={country}
                  value={country}
                  onSelect={() => {
                    // cmdk lowercases the value it passes back — use the original name.
                    onChange(country === value ? '' : country);
                    setOpen(false);
                  }}
                >
                  <Check
                    className={cn('mr-2 h-4 w-4', value === country ? 'opacity-100' : 'opacity-0')}
                    aria-hidden
                  />
                  {country}
                </CommandItem>
              ))}
            </CommandGroup>
          </CommandList>
        </Command>
      </PopoverContent>
    </Popover>
  );
}
